// About story: a condensed tour of Known Limits, "Whose oxygen?", sources, References and On Earth. One card per
// part, lit in turn. Counts come from external_tests.json, o2_sweep.json, references.json and earth_apps.json.
import { loadJSON } from '../data.js';
import { mountStory } from '../story.js';
import { inMoonZone } from '../headline.js';
import { GROUPS } from '../tabs/limits.js';

const esc = (s) => String(s ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
const VERD = { ambient: ['atmosphere', 'ok'], oxidizer_stream: ['burner stream', 'gap'], not_o2: ['not oxygen', 'na'] };

function createVisual(cards) {
  let root;
  const html = (hl) => `<div class="stagecard"><ul class="aboutcards" data-hl="${esc(hl ?? '')}">${cards.map((c) => `<li data-k="${c.k}"><a href="${c.href}">
    <span class="acn">${c.n}</span><span class="acl">${esc(c.label)}</span>${c.extra ?? ''}</a></li>`).join('')}</ul></div>`;
  return {
    mount(el) { root = el; el.innerHTML = `<div class="scene scene-x on">${html('')}</div>`; },
    set(state) { root?.querySelector('.aboutcards')?.setAttribute('data-hl', state.hl); },
    snapshot(state) { return `<div class="snapx">${html(state.hl)}</div>`; },
    dispose() {},
  };
}

export async function render(host) {
  const [ext, sweep, refs, earth] = await Promise.all(['external_tests.json', 'o2_sweep.json', 'references.json', 'earth_apps.json'].map(loadJSON));
  const zone = inMoonZone(ext);
  const vc = sweep.rows.reduce((m, r) => ({ ...m, [r.verdict]: (m[r.verdict] ?? 0) + 1 }), {});
  const srcs = Object.values(ext.sources);
  const sw = refs.software.npm.length + refs.software.python.length;
  const linked = earth.applications.filter((a) => a.related.length);
  const unlinked = earth.applications.filter((a) => !a.related.length);
  const cards = [
    { k: 'limits', n: GROUPS.length, label: 'Known Limits groups', href: '#limits' },
    { k: 'headline', n: zone.length, label: 'solid tests in Moon-base air: burning, not a boundary', href: '#limits/headline' },
    { k: 'oxygen', n: sweep.rows.length, label: 'O2 columns checked: whose oxygen?', href: '#limits/oxygen',
      extra: `<span class="vstrip">${sweep.rows.map((r) => `<i class="v-${VERD[r.verdict]?.[1] ?? 'na'}" title="${esc(`${r.psi_id} "${r.column}": ${VERD[r.verdict]?.[0] ?? r.verdict}`)}"></i>`).join('')}</span>` },
    { k: 'sources', n: srcs.length, label: 'outside sources, with what each does not give', href: '#limits/sources' },
    { k: 'refs', n: refs.psi.investigations.length, label: `PSI datasets cited, plus ${refs.papers.length} papers and ${sw} software packages`, href: '#references' },
    { k: 'earth', n: earth.applications.length, label: 'Earth uses named on the challenge page', href: '#earth' },
  ];
  const steps = [
    { id: 'limits', title: 'Known Limits', state: { hl: 'limits' },
      html: `Known Limits says what each part of this site cannot tell you, in <b>${GROUPS.length}</b> groups. Every page links to it from the header.`,
      chips: [['web/src/tabs/limits.js: every number in it is read from data/processed', 'Known Limits']] },
    { id: 'headline', title: "The headline's limits", state: { hl: 'headline' },
      html: `The headline counts solid-material tests in our sources only. The ${zone.length} inside Moon-base air show burning, not where burning stops.`,
      chips: [[zone.map((t) => `${t.program} ${t.sample}: ${t.material}, ${t.o2_pct[0]}% O2, ${t.pressure_kpa[0]} kPa, ${t.flow_cm_s} cm/s (${t.source.short}, ${t.source.locator}, p.${t.source.printed_page})`).join(' | '), 'Saffire VI · Table 1']] },
    { id: 'oxygen', title: 'Whose oxygen?', state: { hl: 'oxygen' },
      html: `Whose oxygen? Of ${sweep.rows.length} O2 columns in PSI tables, ${vc.ambient ?? 0} are the air around the flame, ${vc.oxidizer_stream ?? 0} a burner stream, ${vc.not_o2 ?? 0} not oxygen.`,
      chips: [[`${sweep.source}: each verdict rests on an exact quote checked against its file`, 'o2_sweep.json']] },
    { id: 'sources', title: 'Outside sources', state: { hl: 'sources' },
      html: `<b>${srcs.length}</b> outside sources, each listed with what it gives and what it does not.`,
      chips: [[srcs.map((s) => s.short).join(' | '), 'sources.json']] },
    { id: 'refs', title: 'References', state: { hl: 'refs' },
      html: `References: <b>${refs.psi.investigations.length}</b> PSI datasets, ${refs.papers.length} reports and papers, ${sw} software packages with licences, and how AI was used.`,
      chips: [['references.json, generated by scripts/05_build_references.py (also references.md in the repository)', 'references.json']] },
    { id: 'earth', title: 'On Earth', state: { hl: 'earth' },
      html: `On Earth: the challenge page names <b>${earth.applications.length}</b> uses. ${linked.length} have related PSI investigations; ${unlinked.length} are adaptations of spacesuit technology.`,
      chips: [[unlinked.map((a) => `${a.title}: ${a.note}`).join(' | '), 'earth_apps.json']] },
  ];
  return mountStory(host, {
    section: 'about', title: 'About', viewHash: 'limits', viewLabel: 'Known Limits',
    intro: `<p class="eyebrow">About</p><h1 class="story-h1">What this site cannot tell you, and where everything comes from</h1>
      <p class="story-sub">Known Limits, sources, references and Earth uses, in brief.</p>`,
    steps, visual: createVisual(cards),
  });
}
